#!/usr/bin/env python
"""Summarize a generated dataset as markdown (family mix, rewards, constraints).

Reads every ``design_*/trajectory.json`` under the dataset root and writes a
report to stdout, or to ``--out``:

    python3 scripts/dataset_stats.py --root dataset --out docs/dataset.md
"""

from __future__ import annotations

import argparse
import json
import statistics
from collections import Counter
from pathlib import Path


def _fmt(values: list[float], places: int = 2) -> str:
    """mean / median / min / max, or a dash when there is nothing to summarize."""
    if not values:
        return "- |, |, | -"
    return " | ".join(
        f"{v:.{places}f}"
        for v in (
            statistics.fmean(values),
            statistics.median(values),
            min(values),
            max(values),
        )
    )


def collect(root: Path) -> dict:
    """Aggregate every trajectory under ``root`` into plain summary dicts."""
    per_family: dict[str, dict] = {}
    operations: Counter[str] = Counter()
    constraint_kinds: Counter[tuple[str, str]] = Counter()
    totals: dict = {
        "designs": 0,
        "unconstrained": 0,
        "rewards": [],
        "steps": [],
        "invalid": 0,
        "all_satisfied": 0,
        "masses": [],
    }

    for path in sorted(root.glob("designs/design_*/trajectory.json")):
        traj = json.loads(path.read_text())
        family = traj.get("family", "unknown")
        metrics = traj.get("final_metrics", {})
        constraints = metrics.get("constraints", {})
        summary = metrics.get("summary", {})
        entry = per_family.setdefault(
            family,
            {"count": 0, "rewards": [], "steps": [], "invalid": 0, "all_satisfied": 0, "masses": []},
        )

        reward = float(metrics.get("total_reward", 0.0))
        steps = int(metrics.get("steps", len(traj.get("actions", []))))
        invalid = int(metrics.get("invalid_actions", 0))
        satisfied = bool(constraints.get("all_measured_satisfied"))
        measured = [
            r for r in constraints.get("results", []) if r.get("status") != "unmeasured"
        ]
        totals["unconstrained"] += int(not measured)
        mass = summary.get("mass_g")

        for bucket in (entry, totals):
            bucket["rewards"].append(reward)
            bucket["steps"].append(steps)
            bucket["invalid"] += invalid
            bucket["all_satisfied"] += int(satisfied)
            if mass is not None:
                bucket["masses"].append(float(mass))
        entry["count"] += 1
        totals["designs"] += 1

        for action in traj.get("actions", []):
            operations[action.get("operation", "?")] += 1
        for result in constraints.get("results", []):
            constraint_kinds[(result["constraint"]["kind"], result["status"])] += 1

    return {
        "totals": totals,
        "per_family": per_family,
        "operations": operations,
        "constraint_kinds": constraint_kinds,
    }


def render(stats: dict, root: Path) -> str:
    totals = stats["totals"]
    n = totals["designs"] or 1
    lines = [
        "# KAIROS dataset",
        "",
        f"Generated by `scripts/generate_dataset.sh` into `{root}/`. Every design is a "
        "validated solid with a recorded expert trajectory: the action sequence that "
        "built it, the shaped reward for each step, and the constraint report its own "
        "natural-language requirement was checked against.",
        "",
        "## Totals",
        "",
        f"- **{totals['designs']} designs**, {sum(stats['operations'].values())} recorded actions",
        f"- **{100.0 * totals['all_satisfied'] / n:.1f}%** satisfy every measurable constraint "
        "in their own requirement",
        f"- **{totals['unconstrained']}** designs have no measurable constraint at all "
        "(nothing was checked for them, so they are not evidence of anything)",
        f"- **{totals['invalid']}** invalid actions across all trajectories",
        "",
        "| metric | mean | median | min | max |",
        "| --- | --- | --- | --- | --- |",
        f"| total reward | {_fmt(totals['rewards'])} |",
        f"| steps | {_fmt(totals['steps'], 1)} |",
        f"| mass (g) | {_fmt(totals['masses'], 1)} |",
        "",
        "## By family",
        "",
        "| family | designs | all constraints met | mean reward | mean steps | mean mass (g) |",
        "| --- | --- | --- | --- | --- | --- |",
    ]

    for family, entry in sorted(stats["per_family"].items()):
        count = entry["count"] or 1
        mass = statistics.fmean(entry["masses"]) if entry["masses"] else float("nan")
        lines.append(
            f"| `{family}` | {entry['count']} | "
            f"{100.0 * entry['all_satisfied'] / count:.0f}% | "
            f"{statistics.fmean(entry['rewards']):.2f} | "
            f"{statistics.fmean(entry['steps']):.1f} | {mass:.1f} |"
        )

    lines += ["", "## Constraint outcomes", "", "| constraint | satisfied | violated | unmeasured |", "| --- | --- | --- | --- |"]
    kinds = sorted({kind for kind, _ in stats["constraint_kinds"]})
    for kind in kinds:
        counts = [stats["constraint_kinds"].get((kind, s), 0) for s in ("satisfied", "violated", "unmeasured")]
        lines.append(f"| `{kind}` | {counts[0]} | {counts[1]} | {counts[2]} |")
    lines += [
        "",
        "Constraints KAIROS cannot yet measure (minimum wall thickness, symmetry) are "
        "reported `unmeasured` and excluded from satisfaction rates rather than counted "
        "as passing, rewards must never claim credit for unchecked requirements.",
        "",
        "## Action mix",
        "",
        "| operation | count | share |",
        "| --- | --- | --- |",
    ]
    total_ops = sum(stats["operations"].values()) or 1
    for op, count in stats["operations"].most_common():
        lines.append(f"| `{op}` | {count} | {100.0 * count / total_ops:.1f}% |")

    lines += [
        "",
        "## Files per design",
        "",
        "`model.FCStd` (parametric document), `model.step` (B-rep exchange), `model.stl` "
        "(0.3 mm deflection mesh), four rendered views (`iso`, `front`, `top`, `right`), "
        "`state.json` (geometry snapshot), `requirements.json` (structured spec), and "
        "`trajectory.json` (actions, rewards, constraint report).",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path("dataset"))
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args()

    report = render(collect(args.root), args.root)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(report)
        print(f"wrote {args.out}")
    else:
        print(report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
